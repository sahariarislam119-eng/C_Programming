#include<stdio.h>
int main()
{
    // Integer array
    int arr1[3]={1,2,3};
    printf("%d, %d, %d\n",arr1[0], arr1[1],arr1[2]);

    // Float array
    float arr2[3]={1.98,3.79,9.08};
    printf("%f, %f, %f\n",arr2[0], arr2[1],arr2[2]);

    // Character array
    char arr3[3]={65,'Y','K'};
    printf("%c, %c, %c\n",arr3[0], arr3[1],arr3[2]);

    return 0;
}